use std::collections::VecDeque;
use std::sync::{Arc, Mutex};

const MAX_ENTRIES: usize = 128;
const MAX_BYTES: usize = 16 * 1024 * 1024;

#[derive(Debug)]
struct CompiledSource {
    source: String,
    bytes: Arc<Vec<u8>>,
}

#[derive(Debug, Default)]
struct Cache {
    entries: VecDeque<CompiledSource>,
    bytes: usize,
}

impl Cache {
    fn get(&mut self, source: &str) -> Option<Arc<Vec<u8>>> {
        let index = self
            .entries
            .iter()
            .position(|entry| entry.source == source)?;
        let entry = self.entries.remove(index).unwrap();
        let bytes = entry.bytes.clone();
        self.entries.push_back(entry);
        Some(bytes)
    }
}

/// Shares only host-generated bytecode, never functions, globals, or JavaScript heap handles.
/// Each host owns a separate cache for its exact JavaScript engine build.
#[derive(Debug, Default)]
pub struct HostJavaScriptCodeCache {
    cache: Mutex<Cache>,
}

impl HostJavaScriptCodeCache {
    /// Reuses exact source under a bounded LRU; failures retain their caller's error type.
    pub fn getOrCompile<E>(
        &self,
        source: &str,
        compile: impl FnOnce() -> Result<Vec<u8>, E>,
    ) -> Result<Arc<Vec<u8>>, E> {
        if let Some(bytes) = self
            .cache
            .lock()
            .expect("JavaScript code cache poisoned")
            .get(source)
        {
            return Ok(bytes);
        }
        // Compilation can be expensive and may run concurrently in independent
        // page runtimes. A miss must not block another page's warm cache hit.
        let bytes = Arc::new(compile()?);
        let size = source.len() + bytes.len();
        if size <= MAX_BYTES {
            let mut cache = self.cache.lock().expect("JavaScript code cache poisoned");
            // Concurrent misses can compile the same source; retain one entry
            // and return its existing bytes without double-counting the budget.
            if let Some(existing) = cache.get(source) {
                return Ok(existing);
            }
            while cache.entries.len() >= MAX_ENTRIES || cache.bytes + size > MAX_BYTES {
                let entry = cache.entries.pop_front().unwrap();
                cache.bytes -= entry.source.len() + entry.bytes.len();
            }
            cache.bytes += size;
            cache.entries.push_back(CompiledSource {
                source: source.to_owned(),
                bytes: bytes.clone(),
            });
        }
        Ok(bytes)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn exact_sources_reuse_bytes_and_failures_do_not_poison_the_cache() {
        let cache = HostJavaScriptCodeCache::default();
        let first = cache
            .getOrCompile("same", || Ok::<_, &str>(vec![1, 2]))
            .unwrap();
        let again = cache
            .getOrCompile::<&str>("same", || panic!("cached source recompiled"))
            .unwrap();
        assert!(Arc::ptr_eq(&first, &again));
        assert_eq!(
            cache.getOrCompile("broken", || Err::<Vec<u8>, _>("syntax")),
            Err("syntax")
        );
        assert_eq!(
            *cache
                .getOrCompile("broken", || Ok::<_, &str>(vec![3]))
                .unwrap(),
            vec![3]
        );
        assert_eq!(
            *cache
                .getOrCompile("different", || Ok::<_, &str>(vec![4]))
                .unwrap(),
            vec![4]
        );
    }

    #[test]
    fn compiling_one_page_does_not_block_another_pages_cache_hit() {
        use std::sync::mpsc;
        use std::time::Duration;

        let cache = Arc::new(HostJavaScriptCodeCache::default());
        let expected = cache.getOrCompile("warm", || Ok::<_, ()>(vec![1])).unwrap();
        let (started, compiling) = mpsc::channel();
        let (release, released) = mpsc::channel();
        let cold_cache = cache.clone();
        let cold = std::thread::spawn(move || {
            cold_cache
                .getOrCompile("cold", || {
                    started.send(()).unwrap();
                    released.recv().unwrap();
                    Ok::<_, ()>(vec![2])
                })
                .unwrap()
        });
        compiling.recv().unwrap();
        let (ready, result) = mpsc::channel();
        let warm_cache = cache.clone();
        let warm = std::thread::spawn(move || {
            let bytes = warm_cache
                .getOrCompile::<()>("warm", || panic!("warm source recompiled"))
                .unwrap();
            ready.send(bytes).unwrap();
        });
        let hit = result.recv_timeout(Duration::from_secs(2));
        // Release both threads even if the regression causes the lookup to block.
        release.send(()).unwrap();
        cold.join().unwrap();
        warm.join().unwrap();
        assert!(Arc::ptr_eq(
            &expected,
            &hit.expect("warm lookup blocked behind compilation")
        ));
    }

    #[test]
    fn concurrent_misses_keep_one_entry_and_one_budget_charge() {
        let cache = Arc::new(HostJavaScriptCodeCache::default());
        let (started, compiling) = std::sync::mpsc::channel();
        let mut releases = Vec::new();
        let mut workers = Vec::new();
        for _ in 0..2 {
            let cache = cache.clone();
            let started = started.clone();
            let (release, released) = std::sync::mpsc::channel();
            releases.push(release);
            workers.push(std::thread::spawn(move || {
                cache
                    .getOrCompile("same", || {
                        started.send(()).unwrap();
                        released.recv().unwrap();
                        Ok::<_, ()>(vec![7, 8])
                    })
                    .unwrap()
            }));
        }
        let timeout = std::time::Duration::from_secs(2);
        let concurrent =
            compiling.recv_timeout(timeout).is_ok() && compiling.recv_timeout(timeout).is_ok();
        // Ensure a locking regression reports a failure instead of deadlocking the suite.
        for release in releases {
            let _ = release.send(());
        }
        let bytes = workers
            .into_iter()
            .map(|worker| worker.join().unwrap())
            .collect::<Vec<_>>();
        assert!(concurrent, "independent compilations blocked each other");
        assert!(Arc::ptr_eq(&bytes[0], &bytes[1]));
        let stored = cache.cache.lock().unwrap();
        assert_eq!(stored.entries.len(), 1);
        assert_eq!(stored.bytes, "same".len() + 2);
    }

    #[test]
    fn evicts_old_entries_and_does_not_retain_oversized_modules() {
        let cache = HostJavaScriptCodeCache::default();
        for i in 0..=MAX_ENTRIES {
            cache
                .getOrCompile(&i.to_string(), || Ok::<_, ()>(vec![1]))
                .unwrap();
        }
        assert_eq!(
            *cache.getOrCompile("0", || Ok::<_, ()>(vec![2])).unwrap(),
            vec![2]
        );
        let huge = "x".repeat(MAX_BYTES);
        cache.getOrCompile(&huge, || Ok::<_, ()>(vec![1])).unwrap();
        assert!(!cache
            .cache
            .lock()
            .unwrap()
            .entries
            .iter()
            .any(|entry| entry.source == huge));
    }
}
