//! Pinned, single-file GGUF chat models for the embedded llama.cpp runtime.
//! Repository metadata and LFS SHA-256 values checked on 2026-11-01.
//! Quantized repositories may be maintained by the authors or community publishers.

use crate::LocalModelManifest::{
    LocalEngineKind, LocalEngineRequirement, LocalModelDriver, LocalModelFile,
    LocalModelInstallSource, LocalModelKind, LocalModelManifest, LocalModelSource,
    LocalModelSourceKind,
};

struct GgufChatModel {
    id: &'static str,
    name: &'static str,
    description: &'static str,
    repository: &'static str,
    revision: &'static str,
    filename: &'static str,
    sha256: &'static str,
    byteSize: u64,
    license: &'static str,
    languages: &'static [&'static str],
    tags: &'static [&'static str],
}

/// Builds complete installable manifests while retaining the published GGUF filename.
pub(crate) fn chatManifests() -> Vec<LocalModelManifest> {
    GGUF_CHAT_MODELS
        .iter()
        .map(|entry| {
            let homepage = format!("https://huggingface.co/{}", entry.repository);
            LocalModelManifest {
                id: entry.id.to_string(),
                version: entry.revision.to_string(),
                displayName: format!("{} (llama.cpp)", entry.name),
                description: entry.description.to_string(),
                kind: LocalModelKind::Chat,
                engine: LocalEngineKind::LlamaCpp,
                license: entry.license.to_string(),
                homepage: homepage.clone(),
                languages: entry.languages.iter().map(|s| s.to_string()).collect(),
                tags: ["llm", "offline"]
                    .into_iter()
                    .chain(entry.tags.iter().copied())
                    .map(str::to_string)
                    .collect(),
                engineRequirement: Some(LocalEngineRequirement {
                    engineId: "llama-cpp".to_string(),
                    version: "b11829".to_string(),
                }),
                driver: Some(LocalModelDriver::LlamaCpp {
                    model: entry.filename.to_string(),
                }),
                sources: vec![LocalModelSource {
                    id: "huggingface".to_string(),
                    kind: LocalModelSourceKind::HuggingFace,
                    repository: entry.repository.to_string(),
                    revision: entry.revision.to_string(),
                    baseUrl: format!("{homepage}/resolve/{}", entry.revision),
                }],
                installSource: LocalModelInstallSource::Files,
                files: vec![LocalModelFile {
                    relativePath: entry.filename.to_string(),
                    sha256: entry.sha256.to_string(),
                    byteSize: entry.byteSize,
                    sourceId: "huggingface".to_string(),
                }],
            }
        })
        .collect()
}

