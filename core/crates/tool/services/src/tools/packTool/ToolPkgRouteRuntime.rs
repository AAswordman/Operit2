/// Requires an enabled package installation owned by the current device space.
pub fn requireSpacePackage(package: &str) -> Result<(), String> {
    let record =
        operit_store::ExtensionStore::ExtensionStore::default().record("package", package)?;
    if record.scope != "space" {
        return Err("Device-installed plugin methods cannot be routed".into());
    }
    Ok(())
}

/// Carries the internal argument envelope generated by a decorated method wrapper.
#[derive(serde::Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct Invocation {
    pub binding_key: String,
    pub package_name: String,
    pub method_name: String,
    pub arguments: Vec<Value>,
    pub input_index: Option<usize>,
}

/// Decodes the ordinary Core argument map without interpreting method signatures.
pub fn decode(arguments: CoreValue) -> Result<Invocation, operit_link::CoreLinkError> {
    operit_link::fromCoreValue(arguments)
        .map_err(|error| operit_link::CoreLinkError::new("INVALID_ARGS", error.to_string()))
}

/// Dispatches a plugin call after the Core borrower has released its lock.
pub async fn dispatch(
    handler: AIToolHandler,
    method: &str,
    args: CoreValue,
) -> Result<CoreValue, operit_link::CoreLinkError> {
    let args = decode(args)?;
    requireSpacePackage(&args.package_name).map_err(operit_link::CoreLinkError::internal)?;
    match method {
        "callToolPkgRoute" => {
            let value = invoke(handler, args.package_name, json!({ "op": "call", "bindingKey": args.binding_key, "methodName": args.method_name, "arguments": args.arguments })).await.map_err(operit_link::CoreLinkError::internal)?;
            operit_link::toCoreValue(value)
                .map_err(|error| operit_link::CoreLinkError::internal(error.to_string()))
        }
        "watchToolPkgRoute" => operit_link::toCoreValue(stream(
            handler,
            args.package_name,
            args.binding_key,
            args.method_name,
            args.arguments,
        ))
        .map_err(|error| operit_link::CoreLinkError::internal(error.to_string())),
        _ => Err(operit_link::CoreLinkError::new(
            "INVALID_ROUTE_KIND",
            "Plugin input streams require Link Push",
        )),
    }
}

/// Dispatches one decorated implementation through its package's existing main engine.
pub fn invoke(
    handler: AIToolHandler,
    package: String,
    payload: Value,
) -> Pin<Box<dyn Future<Output = Result<Value, String>> + Send>> {
    let (mut sender, receiver) = tokio::sync::oneshot::channel();
    if let Err(error) = requireSpacePackage(&package) {
        return Box::pin(async move { Err(error) });
    }
    let scheduled = defaultHostRuntimeTaskSchedulerHost().scheduleHostRuntimeAsyncTask(
        "operit-plugin-route-local",
        Box::new(move || {
            Box::pin(async move {
                let result = tokio::select! {
                    biased;
                    _ = sender.closed() => return,
                    result = crate::tools::ToolJsRuntime::invokeToolPkgIpc(
                    &handler,
                    JsToolPkgIpcRequest {
                        dependency_caller: None,
                        package_target: package,
                        caller_context_key: "core-route".into(),
                        target_context_key: None,
                        target_runtime: Some("main".into()),
                        channel: "$route".into(),
                        payload,
                    },
                ) => result,
                };
                let _ = sender.send(result);
            })
        }),
    );
    Box::pin(async move {
        scheduled.map_err(|error| error.to_string())?;
        receiver
            .await
            .map_err(|_| "Plugin route execution was released".to_string())?
    })
}

/// Retains the package engine for the complete lifetime of an implemented stream.
async fn leaseEngine(
    handler: &AIToolHandler,
    package: &str,
) -> Result<ToolPkgExecutionEngineLease, String> {
    let manager =
        RuntimePackageManager::withReady(handler.getOrCreatePackageManager(), |manager| {
            Ok(manager.toolPkgManager().clone())
        })
        .await?;
    let (_, lease) =
        manager.leaseToolPkgMainExecutionEngine(package)?;
    Ok(lease)
}

/// Collects typed plugin output through the runtime's existing Stream abstraction.
struct PluginOutputStream {
    receiver: tokio::sync::mpsc::Receiver<Value>,
}

impl operit_util::stream::Stream::Stream for PluginOutputStream {
    type Item = Value;

    /// Collects ordered values until the generator completes or its collector is released.
    fn collect<'a>(
        &'a mut self,
        collector: &'a mut dyn FnMut(Value),
    ) -> operit_util::stream::Stream::CollectFuture<'a> {
        Box::pin(async move {
            while let Some(value) = self.receiver.recv().await {
                collector(value);
            }
        })
    }
}

/// Wraps the implemented Stream in the standard Core descriptor and Watch transport adapter.
pub fn stream(
    handler: AIToolHandler,
    package: String,
    binding: String,
    method: String,
    arguments: Vec<Value>,
) -> CoreStream<Value> {
    let source = CoreStreamSource::new(move |request| {
        let (sender, receiver) = tokio::sync::mpsc::channel::<Value>(1);
        let handler = handler.clone();
        let package = package.clone();
        let payload = json!({ "op":"open", "bindingKey":binding, "methodName":method, "arguments":arguments });
        defaultHostRuntimeTaskSchedulerHost().scheduleHostRuntimeAsyncTask("operit-plugin-route-stream", Box::new(move || Box::pin(async move {
            let result = async {
                let _engine = leaseEngine(&handler, &package).await?;
                let id = invoke(handler.clone(), package.clone(), payload).await?;
                let id = id.as_str().ok_or("Plugin Stream did not return an identity")?.to_string();
                loop {
                    let next = invoke(handler.clone(), package.clone(), json!({ "op":"next", "id":id }));
                    tokio::pin!(next);
                    let result = tokio::select! {
                        biased;
                        _ = sender.closed() => {
                            let closing = invoke(handler.clone(), package.clone(), json!({ "op":"close", "id":id }));
                            let (_, closed) = tokio::join!(&mut next, closing);
                            closed?;
                            return Ok::<(), String>(());
                        },
                        value = &mut next => value,
                    };
                    let item = match result {
                        Ok(value) => value,
                        Err(error) => {
                            invoke(handler.clone(), package.clone(), json!({ "op":"close", "id":id })).await?;
                            return Err(error);
                        }
                    };
                    let done = item.get("done").and_then(Value::as_bool).ok_or("Plugin Stream returned an invalid iterator result")?;
                    let sent = sender.send(item).await;
                    if done || sent.is_err() {
                        invoke(handler.clone(), package.clone(), json!({ "op":"close", "id":id })).await?;
                        return Ok(());
                    }
                }
            }.await;
            if let Err(error) = result { let _ = sender.send(json!({ "error":error })).await; }
        }))).map_err(|error| CoreLinkError::internal(error.to_string()))?;
        Ok(operit_rslink_runtime::core_json_event_stream(
            PluginOutputStream { receiver },
            request,
        ))
    });
    CoreStream::fromSource(Arc::new(source))
}

/// Owns the JavaScript consumer while a typed Rust ReverseStream is being collected.
struct PluginInputLease {
    handler: AIToolHandler,
    package: String,
    id: Option<String>,
    engine: Option<ToolPkgExecutionEngineLease>,
}

/// Collects the existing typed ReverseStream and completes the actual decorated async body.
pub async fn consume(
    handler: AIToolHandler,
    package: String,
    payload: Value,
    mut input: operit_util::stream::ReverseStream::ReverseStream<Value>,
) -> Result<(), String> {
    let engine = leaseEngine(&handler, &package).await?;
    let id = invoke(handler.clone(), package.clone(), payload).await?;
    let id = id
        .as_str()
        .ok_or("Plugin ReverseStream did not return an identity")?
        .to_string();
    let mut lease = PluginInputLease {
        handler,
        package,
        id: Some(id),
        engine: Some(engine),
    };
    while let Some(value) = input.recv().await {
        invoke(
            lease.handler.clone(),
            lease.package.clone(),
            json!({ "op":"pushItem", "id":lease.id, "value":value }),
        )
        .await?;
    }
    let result = invoke(
        lease.handler.clone(),
        lease.package.clone(),
        json!({ "op":"pushClose", "id":lease.id }),
    )
    .await;
    lease.id.take();
    result?;
    Ok(())
}

impl Drop for PluginInputLease {
    /// Cancels the actual consumer when its ReverseStream owner releases the invocation.
    fn drop(&mut self) {
        if let Some(id) = self.id.take() {
            let engine = self.engine.take();
            let work = invoke(
                self.handler.clone(),
                self.package.clone(),
                json!({ "op":"pushAbort", "id":id }),
            );
            let _ = defaultHostRuntimeTaskSchedulerHost().scheduleHostRuntimeAsyncTask(
                "operit-plugin-route-input-release",
                Box::new(move || {
                    Box::pin(async move {
                        if let Err(error) = work.await {
                            operit_util::AppLogger::AppLogger::e("ToolPkgRoute", &error);
                        }
                        drop(engine);
                    })
                }),
            );
        }
    }
}
