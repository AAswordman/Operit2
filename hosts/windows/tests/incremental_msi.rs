//! Python publisher → shared Rust decoder → Windows CAB codec interoperability.
use base64::Engine;
use operit_host_api::{
    HostManager::HostManager, HttpDownloadControl, RuntimeStorageHost,
};
use operit_host_windows_native::{
    WindowsFileSystemHost, WindowsRuntimeStorageHost, WindowsSystemOperationHost,
};
use operit_util::IncrementalUpdate::{applyPatch, hashSource, UpdateManifest};
use std::sync::Arc;

/// Runs the production decoder with native VFS capabilities and verifies scratch cleanup.
fn reconstruct(
    base: &[u8],
    patch: &[u8],
    manifest: &UpdateManifest,
    control: &HttpDownloadControl,
) -> Result<(), String> {
    let root = tempfile::Builder::new()
        .prefix("operit 更新 ' & ")
        .tempdir()
        .unwrap();
    let storage = Arc::new(WindowsRuntimeStorageHost::new(
        root.path().into(),
        root.path().join("workspaces"),
    ));
    let mut context = HostManager::withFileSystemHost(Arc::new(WindowsFileSystemHost::new()))
        .withRuntimeStorageHost(storage.clone())
        .withRuntimeStorageWriteHost(storage.clone());
    context.systemOperationHost = Some(Arc::new(WindowsSystemOperationHost::new()));
    let directory = "runtime/temp/application_updates/test";
    storage
        .writeBytes(&format!("{directory}/base.msi"), base)
        .unwrap();
    storage
        .writeBytes(&format!("{directory}/patch.gz"), patch)
        .unwrap();
    let vfs = context.vfs().unwrap();
    let base = vfs
        .file("/operitapp/data/temp/application_updates/test/base.msi")
        .unwrap();
    let patch = vfs
        .file("/operitapp/data/temp/application_updates/test/patch.gz")
        .unwrap();
    let destination = format!("{directory}/result.msi");
    let result = applyPatch(
        &base,
        &patch,
        manifest,
        &manifest.patches[0],
        &context,
        &destination,
        control,
    );
    assert_eq!(
        hashSource(&base, &HttpDownloadControl::new()).unwrap(),
        (
            manifest.patches[0].baseSha256.clone(),
            manifest.patches[0].baseSize
        )
    );
    assert_eq!(
        storage
            .list("runtime/temp/application_updates")
            .unwrap()
            .len(),
        1,
        "Scratch job leaked"
    );
    if result.is_ok() {
        let output = vfs
            .file("/operitapp/data/temp/application_updates/test/result.msi")
            .unwrap();
        assert_eq!(
            hashSource(&output, control).unwrap(),
            (manifest.sha256.clone(), manifest.size)
        );
    } else {
        assert!(!storage.exists(&destination).unwrap());
    }
    result
}

/// Restores the exact MSI generated by Python, including from Unicode and shell-metacharacter paths.
#[test]
fn python_cabinet_patch_round_trip() {
    let fixture: serde_json::Value = serde_json::from_str(include_str!(
        "../../../tools/tests/fixtures/msi_cabinet_delta.json"
    ))
    .unwrap();
    let decode = |key: &str| {
        base64::engine::general_purpose::STANDARD
            .decode(fixture[key].as_str().unwrap())
            .unwrap()
    };
    let manifest = serde_json::from_value(fixture["manifest"].clone()).unwrap();
    reconstruct(
        &decode("base"),
        &decode("patch"),
        &manifest,
        &HttpDownloadControl::new(),
    )
    .unwrap();
    let control = HttpDownloadControl::new();
    control.cancel();
    assert!(reconstruct(&decode("base"), &decode("patch"), &manifest, &control).is_err());
    let mut corrupted = decode("patch");
    corrupted[100] ^= 1;
    assert!(reconstruct(
        &decode("base"),
        &corrupted,
        &manifest,
        &HttpDownloadControl::new()
    )
    .is_err());
}

/// Exercises the original local Preview.36 → .37 installers without installing or publishing them.
#[test]
#[ignore = "requires the local release benchmark assets"]
fn preview_36_to_37_real_msi_round_trip() {
    let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../../tools/release");
    let manifest = serde_json::from_slice(
        &std::fs::read(root.join("work/archive-benchmark/update.json")).unwrap(),
    )
    .unwrap();
    let base =
        std::fs::read(root.join("dist/operit2-app-windows-x86_64-2.0.0-preview.36.msi")).unwrap();
    let patch = std::fs::read(root.join("work/archive-benchmark/msi-archive.patch.gz")).unwrap();
    reconstruct(&base, &patch, &manifest, &HttpDownloadControl::new()).unwrap();
}
