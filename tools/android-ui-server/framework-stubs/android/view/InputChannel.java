package android.view;

/** Compile-only declaration of the platform-owned input channel. */
public final class InputChannel {
    /** Allocates the output channel populated by the platform window session. */
    public InputChannel() { throw new UnsupportedOperationException(); }
    /** Releases a channel that was not attached to a receiver. */
    public void dispose() { throw new UnsupportedOperationException(); }
}
