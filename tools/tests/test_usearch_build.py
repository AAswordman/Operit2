"""Exercise USearch incremental builds without downloading or compiling dependencies."""
from contextlib import ExitStack
import importlib.util
from pathlib import Path
import subprocess
import tempfile
import unittest
from unittest.mock import patch


REPO_ROOT = Path(__file__).resolve().parents[2]
SPEC = importlib.util.spec_from_file_location(
    "usearch_build", REPO_ROOT / "plugins/packages/buildin/character_cards/vendor/usearch/build.py",
)
BUILD = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(BUILD)


class USearchBuildTests(unittest.TestCase):
    # Isolate generated files and use an observable compiler in place of Emscripten.
    def setUp(self):
        temporary = tempfile.TemporaryDirectory()
        self.addCleanup(temporary.cleanup)
        self.root = Path(temporary.name)
        self.here = self.root / "plugins/packages/buildin/character_cards/vendor/usearch"
        self.here.mkdir(parents=True)
        (self.here / "index.cpp").write_text("adapter", encoding="utf-8")
        self.source = self.root / "operit-usearch-build" / ("USearch-" + BUILD.REVISION)
        self.source.mkdir(parents=True)
        self.output = self.here.parent.parent / "resources/usearch.wasm"
        self.example = self.root / "plugins/packages/examples/toolpkg_usearch_demo/modules/usearch.wasm"
        patches = ExitStack()
        self.addCleanup(patches.close)
        patches.enter_context(patch.object(BUILD, "ROOT", self.root))
        patches.enter_context(patch.object(BUILD, "HERE", self.here))
        patches.enter_context(patch.object(BUILD.tempfile, "gettempdir", return_value=str(self.root)))
        patches.enter_context(patch.dict(BUILD.os.environ, {"EMXX": "test-em++"}))
        self.compiler = patches.enter_context(patch.object(BUILD.subprocess, "run", side_effect=self.compile))
        self.download = patches.enter_context(patch.object(BUILD.urllib.request, "urlretrieve"))

    # Materialize the compiler output at the exact requested destination.
    def compile(self, command, **kwargs):
        Path(command[command.index("-o") + 1]).write_bytes(b"compiled wasm")

    # Reuse requires both matching inputs and exact generated bytes.
    def test_incremental_build_rebuilds_changed_sources_missing_or_changed_outputs(self):
        BUILD.build()
        BUILD.build()
        self.assertEqual(self.compiler.call_count, 1)
        self.output.unlink()
        BUILD.build()
        self.assertEqual(self.compiler.call_count, 2)
        self.output.write_bytes(b"damaged output")
        BUILD.build()
        self.assertEqual(self.compiler.call_count, 3)
        (self.here / "index.cpp").write_text("changed adapter", encoding="utf-8")
        BUILD.build()
        self.assertEqual(self.compiler.call_count, 4)
        self.assertEqual(self.output.read_bytes(), self.example.read_bytes())
        self.download.assert_not_called()

    # Recreating the example's copy must not recompile an unchanged owner output.
    def test_cached_build_restores_missing_example_module(self):
        BUILD.build()
        self.example.unlink()
        BUILD.build()
        self.assertEqual(self.compiler.call_count, 1)
        self.assertEqual(self.example.read_bytes(), self.output.read_bytes())

    # Failed compilation must remain an error and must never become a reusable build.
    def test_compiler_failure_does_not_publish_success_state(self):
        self.compiler.side_effect = subprocess.CalledProcessError(1, "test-em++")
        with self.assertRaises(subprocess.CalledProcessError):
            BUILD.build()
        self.assertFalse((self.here.parent.parent / ".cache/usearch-build.json").exists())
        self.assertFalse(self.example.exists())


if __name__ == "__main__":
    unittest.main()
